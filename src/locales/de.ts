function count(n: string, singular: string, plural: string) {
  return `${n} ${Number(n) === 1 ? singular : plural}`;
}

function label(value: string): string {
  if (de[value]) return de[value];
  // Parameters can themselves be messages, e.g. a service reminder title.
  for (const [pattern, replacement] of dePatterns) {
    const match = value.match(pattern);
    if (match) {
      const result = replacement(...match.slice(1));
      if (result !== value) return result;
    }
  }
  return value.split(/( · | × )/).map(part => de[part] ?? part).join("");
}

